"""Export the navigation rules' numbers and phrases to models/nav_config.json for the phone app.

    python scripts/export_nav_config.py          # rewrite models/nav_config.json

The JSON holds the navigator section of configs/default.yaml with every default filled
in (src/navigator.py NavigatorConfig), the spoken name of every class, and the
fine-tuned model's per-class detection thresholds, and the phone app's own numbers
("app": the `mobile:` section plus camera.stale_timeout). The phone app loads this file instead
of its own copy of the numbers; docs/navigation_spec.md describes how they are used and
tests/golden/nav_cases.json pins the expected messages.

tests/test_nav_golden.py fails if this file is out of date with configs/default.yaml:
re-run this script after changing the config.
"""

from __future__ import annotations

import dataclasses
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.navigator import NavigatorConfig, display_name  # noqa: E402

FORMAT_VERSION = 1
OUT = ROOT / "models" / "nav_config.json"


def _plain(value: Any) -> Any:
    """Tuples -> lists, mappings -> dicts with sorted keys, recursively (stable JSON)."""
    if isinstance(value, Mapping):
        return {str(k): _plain(value[k]) for k in sorted(value)}
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    return value


def build_nav_config(config: Path = ROOT / "configs" / "default.yaml",
                     classes_file: Path = ROOT / "configs" / "classes.yaml") -> dict[str, Any]:
    cfg = yaml.safe_load(config.read_text())
    classes: Sequence[str] = yaml.safe_load(classes_file.read_text())["names"]
    nav = NavigatorConfig.from_dict(cfg.get("navigator", {}))
    navigator = {f.name: _plain(getattr(nav, f.name)) for f in dataclasses.fields(nav)}
    named = sorted(set(classes) | set(nav.severity) | set(nav.speak_conf) | set(nav.hazard_classes))
    ft = cfg.get("detector", {}).get("finetuned", {}) or {}
    default_conf = float(ft.get("conf", 0.25))
    app = _plain({**(cfg.get("mobile") or {}),
                  "stale_timeout": float(cfg.get("camera", {}).get("stale_timeout", 1.5))})
    return {
        "format_version": FORMAT_VERSION,
        "source": "configs/default.yaml (navigator, detector.finetuned, mobile, camera.stale_timeout); generated by scripts/export_nav_config.py",
        "spec": "docs/navigation_spec.md",
        "golden_cases": "tests/golden/nav_cases.json",
        "classes": list(classes),
        "navigator": navigator,
        "spoken_names_resolved": {c: display_name(c, nav) for c in named},
        "detection": {
            "model": Path(ft.get("model_path", "")).parent.name or None,
            "imgsz": ft.get("imgsz"),
            "default_conf": default_conf,
            "class_conf": {c: float((ft.get("class_conf") or {}).get(c, default_conf)) for c in classes},
        },
        "app": app,
    }


def render(data: Mapping[str, Any]) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(build_nav_config()))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
